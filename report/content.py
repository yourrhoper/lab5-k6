def ms(v):
    return f'{v:,.0f}'.replace(',', ' ') + ' мс' if v < 10000 else f'{v/1000:.1f} с'.replace('.', ',')


def n(v, d=0):
    s = f'{v:,.{d}f}'.replace(',', ' ').replace('.', ',')
    return s


def thr(summary, metric, stat):
    m = summary['metrics'][metric]
    return m.get(stat, m.get('value'))


ORDER = ['GET /api/health', 'GET /api/achievements', 'GET /api/dictionaries', 'POST /api/auth/login', 'POST /api/achievements', 'GET /api/achievements/:id']


def endpoints_table(eps, W):
    by = {e['name']: e for e in eps}
    rows = []
    for name in ORDER:
        e = by.get(name)
        if not e:
            continue
        rows.append([name, n(e['count']), n(e['rps'], 1), n(e['avg']), n(e['p50']), n(e['p95']), n(e['p99']), n(e['max']), n(e['err'], 2)])
    return table(['Запрос', 'Кол-во', 'RPS', 'avg, мс', 'p50, мс', 'p95, мс', 'p99, мс', 'max, мс', 'Ошибки, %'], rows,
                 [2800, 1000, 750, 850, 850, 850, 850, 950, 1006], align=['left'] + ['center'] * 8, size=22)


