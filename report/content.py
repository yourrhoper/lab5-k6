            f'с нагрузкой на всех ступенях и на ×5 составляет {n(b5["rps"])} RPS против {n(a5["rps"])} RPS у исходной версии '
            f'(в {n(b5["rps"]/a5["rps"], 1)} раза больше). Лёгкие запросы больше не страдают от входа: p95 сценария browse на ступени ×5 — '
            f'{n(b5["p95_browse"])} мс против {n(a5["p95_browse"])} мс, вход — {n(b5["p95_login"])} мс против {n(a5["p95_login"])} мс. '
            f'Все пороги SLA выполнены на всех ступенях (k6 завершился с кодом 0, p95 всех запросов — {ms(SA["metrics"]["http_req_duration"]["p(95)"])}, '
            f'ошибок 0 %). Это подтверждает, что узким местом исходной версии была именно блокировка основного потока синхронным хэшированием, '
